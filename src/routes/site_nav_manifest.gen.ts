import type { Gen } from '@fuzdev/gro/gen.ts';

import { families, family_failures, family_ids } from '#routes/coherence/coherence.ts';
import {
	coherence_family_paths,
	coherence_gaps_page,
	coherence_inventory_ids,
	coherence_inventory_pages
} from '#routes/coherence/coherence_pages.ts';
import { gaps_sections } from '#routes/coherence/gaps_sections.ts';
import { glossary_groups } from '#routes/glossary/glossary.ts';
import { project_pages } from '#routes/projects/project_page.ts';

/**
 * Writes what the sidebar lists under the coherence and projects sections, so the
 * site's layout loads a few names and not the data files they come from.
 *
 * @nodocs
 */
export const gen: Gen = ({ origin_path }) => {
	const coherence_families = family_ids.map((id) => ({
		label: families[id].label,
		path: coherence_family_paths[id],
		failures: family_failures(id).map((f) => ({ id: f.id, name: f.name }))
	}));
	const coherence_tables = [
		{ ...coherence_gaps_page, sections: gaps_sections },
		...coherence_inventory_ids.map((id) => ({
			title: coherence_inventory_pages[id].title,
			path: coherence_inventory_pages[id].path,
			sections: {}
		}))
	];
	const projects = project_pages.map((page) => ({
		name: page.project.name,
		sections: page.sections
	}));
	return `// generated by ${origin_path} - do not edit

/** The coherence section's family pages, each with its failures' anchors. */
export const nav_coherence_families = ${JSON.stringify(coherence_families)} as const;

/** The coherence section's other pages, the gaps and then each table, with a page's own sections. */
export const nav_coherence_tables = ${JSON.stringify(coherence_tables)} as const;

/** The glossary page's sections, by anchor. */
export const nav_glossary_sections: Record<string, string> = ${JSON.stringify(glossary_groups)};

/** The stack's projects, each with its page's sections by anchor. */
export const nav_projects: ReadonlyArray<{ name: string; sections: Record<string, string> }> = ${JSON.stringify(projects)};
`;
};
