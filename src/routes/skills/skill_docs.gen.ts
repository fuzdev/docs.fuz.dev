import type { Gen } from '@fuzdev/gro/gen.ts';
import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { join, basename } from 'node:path';

const SKILLS_DIR = join(process.cwd(), 'skills');

const parse_frontmatter = (
	raw: string
): { content: string; frontmatter: Record<string, string> } => {
	const frontmatter: Record<string, string> = {};
	if (!raw.startsWith('---')) return { content: raw, frontmatter };
	const end = raw.indexOf('---', 3);
	if (end === -1) return { content: raw, frontmatter };
	const yaml_block = raw.slice(3, end).trim();
	for (const line of yaml_block.split('\n')) {
		// top-level keys only: an indented line belongs to a nested map like `metadata`
		if (line.startsWith(' ') || line.startsWith('\t')) continue;
		const colon = line.indexOf(':');
		if (colon === -1) continue;
		const key = line.slice(0, colon).trim();
		const value = line.slice(colon + 1).trim();
		if (key && value) frontmatter[key] = value;
	}
	return { content: raw.slice(end + 3).trimStart(), frontmatter };
};

const HEADING_RE = /^#\s+(.+)$/m;

const extract_title = (content: string): string => {
	const match = HEADING_RE.exec(content);
	return match?.[1]?.trim() ?? 'Untitled';
};

const to_slug = (filename: string): string => basename(filename, '.md').replaceAll('_', '-');

// Match either an inline backtick code span (preserved) or a relative `.md` path (rewritten).
// The path arm is anchored: `./` or `../` (one or more) + name segments + trailing name + `.md`.
const REL_MD_PATH_RE = /(`[^`\n]*`)|((?:\.{1,2}\/)+(?:[\w-]+\/)*[\w-]+)\.md\b/g;

// SKILL.md is rendered at the skill's directory route, not a `/SKILL` subroute,
// so a `.md`-stripped `./SKILL` or `../SKILL` would 404. Map to the directory instead.
const SKILL_PATH_RE = /^((?:\.{1,2}\/)+)SKILL$/;

const rewrite_md_path = (path: string): string => {
	const skill = SKILL_PATH_RE.exec(path);
	if (skill) return skill[1]!.replace(/\/$/, ''); // `./SKILL` → `.`, `../SKILL` → `..`
	return path;
};

/**
 * Strips `.md` extensions from bare relative paths for web route resolution.
 * ./foo.md → ./foo, ./references/foo.md → ./references/foo, ../SKILL.md → ..
 * Skips fenced code blocks and inline backtick code spans.
 */
const rewrite_md_links = (content: string): string => {
	const lines = content.split('\n');
	let in_code_block = false;

	for (let i = 0; i < lines.length; i++) {
		if (lines[i]!.trimStart().startsWith('```')) {
			in_code_block = !in_code_block;
			continue;
		}
		if (in_code_block) continue;

		lines[i] = lines[i]!.replace(
			REL_MD_PATH_RE,
			(_match, code_span, path) => code_span ?? rewrite_md_path(path)
		);
	}

	return lines.join('\n');
};

export const gen: Gen = ({ origin_path }) => {
	const banner = `// generated by ${origin_path} - do not edit`;
	const svelte_banner = `<!-- generated by ${origin_path} -->`;
	const skills_route_dir = join(process.cwd(), 'src/routes/skills');

	// auto-discover skills
	const skill_dirs = readdirSync(SKILLS_DIR, { withFileTypes: true })
		.filter((d) => d.isDirectory() && existsSync(join(SKILLS_DIR, d.name, 'SKILL.md')))
		.map((d) => d.name)
		.sort();

	const skills_meta: Array<{
		name: string;
		path: string;
		references_path: string | null;
		title: string;
		description: string;
		references: Array<{ slug: string; path: string; title: string; description: string }>;
	}> = [];

	const output_files: Array<{ content: string; filename: string }> = [];

	for (const skill_name of skill_dirs) {
		const skill_dir = join(SKILLS_DIR, skill_name);
		const skill_route_dir = join(skills_route_dir, skill_name);

		// read SKILL.md
		const skill_raw = readFileSync(join(skill_dir, 'SKILL.md'), 'utf-8');
		const { content: skill_content, frontmatter } = parse_frontmatter(skill_raw);
		const skill_title = extract_title(skill_content);
		const skill_description = frontmatter.description ?? '';

		// read references if directory exists
		const refs_dir = join(skill_dir, 'references');
		const has_refs = existsSync(refs_dir);
		const references: Array<{
			slug: string;
			title: string;
			description: string;
			content: string;
			source: string;
		}> = [];

		if (has_refs) {
			const ref_files = readdirSync(refs_dir)
				.filter((f) => f.endsWith('.md'))
				.sort();
			for (const filename of ref_files) {
				const raw = readFileSync(join(refs_dir, filename), 'utf-8');
				const { content: ref_content, frontmatter: ref_frontmatter } = parse_frontmatter(raw);
				const description = ref_frontmatter.description;
				if (!description) {
					throw new Error(
						`missing \`description\` frontmatter in ${join(refs_dir, filename)} - every skill reference needs a one-line description`
					);
				}
				const title = extract_title(ref_content);
				const slug = to_slug(filename);
				const content = rewrite_md_links(ref_content);
				const source = `skills/${skill_name}/references/${filename}`;
				references.push({ slug, title, description, content, source });
			}
		}

		// collect metadata for manifest
		const skill_path = `/skills/${skill_name}`;
		skills_meta.push({
			name: skill_name,
			path: skill_path,
			references_path: references.length > 0 ? `${skill_path}/references` : null,
			title: skill_title,
			description: skill_description,
			references: references.map((r) => ({
				slug: r.slug,
				path: `${skill_path}/references/${r.slug}`,
				title: r.title,
				description: r.description
			}))
		});

		// generate per-skill skill_data.ts
		output_files.push({
			content: `${banner}

import type {SkillDoc} from '../skill_doc.ts';

export const skill_main: SkillDoc = ${JSON.stringify({ slug: 'overview', title: skill_title, content: rewrite_md_links(skill_content), source: `skills/${skill_name}/SKILL.md` })};

export const skill_references: Array<SkillDoc> = ${JSON.stringify(references.map((r) => ({ slug: r.slug, title: r.title, content: r.content, source: r.source })))};

${banner}
`,
			filename: join(skill_route_dir, 'skill_data.ts')
		});

		// generate skill index +page.svelte
		output_files.push({
			content: `${svelte_banner}

<script lang="ts">
	import SkillDocPage from '../SkillDocPage.svelte';
	import {skill_main} from './skill_data.ts';
</script>

<SkillDocPage doc={skill_main} skill="${skill_name}" base="/skills/${skill_name}/" />

${svelte_banner}
`,
			filename: join(skill_route_dir, '+page.svelte')
		});

		// generate references index +page.svelte
		if (references.length > 0) {
			output_files.push({
				content: `${svelte_banner}

<script lang="ts">
	import {resolve} from '$app/paths';

	import {skills} from '#routes/skills/skills_manifest.ts';

	const skill = skills.find((s) => s.name === '${skill_name}')!;
</script>

<svelte:head>
	<title>references - ${skill_name} - docs.fuz.dev</title>
</svelte:head>

<h1>References</h1>
<p>
	The reference documents of the <a href={resolve(skill.path)}>${skill_name}</a> skill, each read
	when its task comes up.
</p>
<ul>
	{#each skill.references as ref (ref.slug)}
		<li>
			<a href={resolve(ref.path)}>{ref.title}</a>
			— {ref.description}
		</li>
	{/each}
</ul>

${svelte_banner}
`,
				filename: join(skill_route_dir, 'references', '+page.svelte')
			});
		}

		// generate per-reference +page.svelte files
		for (let i = 0; i < references.length; i++) {
			const ref = references[i]!;
			output_files.push({
				content: `${svelte_banner}

<script lang="ts">
	import SkillDocPage from '../../../SkillDocPage.svelte';
	import {skill_references} from '../../skill_data.ts';
</script>

<SkillDocPage
	doc={skill_references[${i}]!}
	skill="${skill_name}"
	base="/skills/${skill_name}/references/"
/>

${svelte_banner}
`,
				filename: join(skill_route_dir, 'references', ref.slug, '+page.svelte')
			});
		}
	}

	// generate skills_manifest.ts
	const manifest_content = `${banner}

export interface SkillMeta {
	name: string;
	/** The skill's route. */
	path: string;
	/** The route of the references index, or \`null\` for a skill without references. */
	references_path: string | null;
	title: string;
	/** The frontmatter description an agent matches a task against. */
	description: string;
	references: ReadonlyArray<{slug: string; path: string; title: string; description: string}>;
}

// literal, so a \`path\` is a route \`resolve\` accepts
export const skills = ${JSON.stringify(skills_meta)} as const satisfies ReadonlyArray<SkillMeta>;

${banner}
`;

	return [{ content: manifest_content, filename: 'skills_manifest.ts' }, ...output_files];
};
